#!/usr/bin/env python3
"""Generate bigquery/seed.sql with demo FX positions for scenario 03.

The data is deterministic: the same --anchor date always produces the same
file (fixed random seed). Dates are placed relative to the anchor, so the
demo can be refreshed later by re-running with a newer anchor.

Usage:
    python generate_seed.py --anchor 2026-10-19
    python generate_seed.py                  # anchor = today
"""
import argparse
import random
import sys
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

SEED = 42

# Fictitious counterparties: (name, direction, currency, typical amount range)
COUNTERPARTIES = [
    ("Nordwind Cloud GmbH",       "payable",    "EUR", (2_000, 9_000)),
    ("Helix Software BV",         "payable",    "EUR", (1_500, 6_000)),
    ("Alpenlicht Engineering AG", "payable",    "CHF", (3_000, 8_000)),
    ("Bluefin Analytics Inc.",    "payable",    "USD", (1_000, 5_000)),
    ("Quarry Data Systems LLC",   "payable",    "USD", (2_500, 7_500)),
    ("Thames Render Ltd",         "payable",    "GBP", (1_000, 4_000)),
    ("Lumen Logistics SARL",      "receivable", "EUR", (4_000, 12_000)),
    ("Kestrel Media Ltd",         "receivable", "GBP", (3_000, 9_000)),
    ("Pinecrest Retail Corp.",    "receivable", "USD", (2_000, 6_000)),
]

PAYMENT_TERMS = [14, 30, 45, 60]
N_POSITIONS = 22
SHARE_SETTLED = 0.25


def business_day(d: date) -> date:
    """Shift a weekend date back to Friday."""
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d


def generate(anchor: date) -> list[dict]:
    rnd = random.Random(SEED)
    # Every counterparty at least once, the rest drawn at random.
    picks = COUNTERPARTIES + [rnd.choice(COUNTERPARTIES)
                              for _ in range(N_POSITIONS - len(COUNTERPARTIES))]
    rows = []
    for i, (name, direction, ccy, (lo, hi)) in enumerate(picks):
        # The first document of each counterparty is recent and still open,
        # so every currency shows up in the open position.
        always_open = i < len(COUNTERPARTIES)
        max_age = 45 if always_open else 95
        booked = business_day(anchor - timedelta(days=rnd.randint(5, max_age)))
        due = booked + timedelta(days=rnd.choice(PAYMENT_TERMS))
        amount = Decimal(rnd.randint(lo * 100, hi * 100)) / 100

        # Long overdue documents are usually paid by now; a few stay overdue.
        overdue = due < anchor - timedelta(days=7)
        p_settled = 0.0 if always_open else (0.85 if overdue else SHARE_SETTLED)
        settled = None
        last_possible = min(due, anchor - timedelta(days=1))
        if rnd.random() < p_settled and last_possible > booked:
            span = (last_possible - booked).days
            settled = business_day(booked + timedelta(days=rnd.randint(1, span)))
            if settled <= booked:
                settled = None

        rows.append({
            "position_id": None,
            "direction": direction,
            "counterparty": name,
            "currency": ccy,
            "amount": amount,
            "booked_date": booked,
            "due_date": due,
            "settled_date": settled,
        })
    # Number documents in date order, separately for AP and AR.
    rows.sort(key=lambda r: (r["booked_date"], r["counterparty"]))
    counters = {"payable": 0, "receivable": 0}
    for r in rows:
        counters[r["direction"]] += 1
        prefix = "AP" if r["direction"] == "payable" else "AR"
        r["position_id"] = f"{prefix}-{counters[r['direction']]:04d}"
    return rows


def validate(rows: list[dict], anchor: date) -> None:
    """The rules BigQuery cannot enforce (no CHECK constraints)."""
    ids = [r["position_id"] for r in rows]
    assert len(ids) == len(set(ids)), "duplicate position_id"
    for r in rows:
        assert r["direction"] in ("payable", "receivable"), r
        assert r["currency"] in ("EUR", "USD", "CHF", "GBP"), r
        assert r["amount"] > 0, r
        assert r["due_date"] >= r["booked_date"], r
        assert r["booked_date"] < anchor, r
        if r["settled_date"] is not None:
            assert r["booked_date"] < r["settled_date"] < anchor, r


def to_sql(rows: list[dict], anchor: date) -> str:
    def lit(v):
        if v is None:
            return "NULL"
        if isinstance(v, Decimal):
            return f"NUMERIC '{v:.2f}'"
        if isinstance(v, date):
            return f"DATE '{v.isoformat()}'"
        return "'" + str(v).replace("'", "\\'") + "'"

    cols = ["position_id", "direction", "counterparty", "currency",
            "amount", "booked_date", "due_date", "settled_date"]
    values = ",\n".join(
        "  (" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows
    )
    return (
        f"-- Generated by generate_seed.py --anchor {anchor.isoformat()} (seed {SEED}). Do not edit by hand.\n"
        "-- Reload is idempotent: the table is emptied and filled again.\n"
        "TRUNCATE TABLE positions;\n\n"
        f"INSERT INTO positions ({', '.join(cols)})\nVALUES\n{values};\n"
    )


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--anchor", type=date.fromisoformat, default=date.today(),
                   help="reference date (YYYY-MM-DD), default: today")
    p.add_argument("--out", type=Path, default=Path(__file__).with_name("seed.sql"))
    args = p.parse_args()

    rows = generate(args.anchor)
    validate(rows, args.anchor)
    args.out.write_text(to_sql(rows, args.anchor), encoding="utf-8", newline="\n")

    open_rows = [r for r in rows if r["settled_date"] is None]
    print(f"{len(rows)} positions ({len(open_rows)} open) -> {args.out}")
    for ccy in ("EUR", "USD", "CHF", "GBP"):
        net = sum((r["amount"] if r["direction"] == "receivable" else -r["amount"])
                  for r in open_rows if r["currency"] == ccy)
        print(f"  {ccy}: net open {net:>12,.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
